/**
 * Exports all 22 class lecture scripts to `scripts/lecture_clips.json` for offline AI voice
 * generation, and updates `src/constants/lectureAudioMap.ts` for any audio files in `assets/audio/`.
 */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const ROOT = path.resolve(__dirname, '..');
const CURRICULUM_PATH = path.join(ROOT, 'src', 'constants', 'curriculum.ts');
const CLIPS_OUT_PATH = path.join(__dirname, 'lecture_clips.json');
const AUDIO_DIR = path.join(ROOT, 'assets', 'audio');
const MAP_OUT_PATH = path.join(ROOT, 'src', 'constants', 'lectureAudioMap.ts');

function loadCurriculumLevels() {
  const source = fs.readFileSync(CURRICULUM_PATH, 'utf8');
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
    },
  });
  const mod = { exports: {} };
  const fn = new Function('exports', 'module', transpiled.outputText);
  fn(mod.exports, mod);
  return mod.exports.SUPERNOVA_LEVELS || [];
}

function buildClipManifest(levels) {
  const clips = [];
  for (const level of levels) {
    for (const cls of level.classes) {
      clips.push({
        key: `${cls.id}-tamil`,
        classNumber: cls.classNumber,
        mode: 'tamil',
        text: cls.rule.tamilMentalModel,
      });
      clips.push({
        key: `${cls.id}-why`,
        classNumber: cls.classNumber,
        mode: 'tamil',
        text: cls.rule.doAndDont.whyTamil,
      });
      clips.push({
        key: `${cls.id}-right`,
        classNumber: cls.classNumber,
        mode: 'english',
        text: cls.rule.doAndDont.right,
      });
    }
  }
  return clips;
}

function findBundledAudioFile(key) {
  const exts = ['.mp3', '.m4a', '.wav'];
  for (const ext of exts) {
    const filePath = path.join(AUDIO_DIR, `${key}${ext}`);
    if (fs.existsSync(filePath)) {
      return `${key}${ext}`;
    }
  }
  return null;
}

function syncLectureAudio() {
  const levels = loadCurriculumLevels();
  const clips = buildClipManifest(levels);

  fs.writeFileSync(CLIPS_OUT_PATH, JSON.stringify(clips, null, 2) + '\n', 'utf8');

  if (!fs.existsSync(AUDIO_DIR)) {
    fs.mkdirSync(AUDIO_DIR, { recursive: true });
  }

  const lines = [
    '/**',
    ' * Auto-generated by `npm run audio:sync` from files placed in `assets/audio/`.',
    ' * Empty by default until pre-generated lecture audio clips are linked.',
    ' */',
    'export const LECTURE_AUDIO_ASSETS: Record<string, number> = {',
  ];

  let linkedCount = 0;
  for (const clip of clips) {
    const filename = findBundledAudioFile(clip.key);
    if (filename) {
      lines.push(`  '${clip.key}': require('../../assets/audio/${filename}'),`);
      linkedCount += 1;
    }
  }
  lines.push('};', '');

  fs.writeFileSync(MAP_OUT_PATH, lines.join('\n'), 'utf8');
  console.log(
    `Exported ${clips.length} lecture scripts to scripts/lecture_clips.json; linked ${linkedCount} audio files from assets/audio/.`
  );
  return { clips, linkedCount, audioDir: AUDIO_DIR };
}

if (require.main === module) {
  syncLectureAudio();
}

module.exports = { syncLectureAudio };
